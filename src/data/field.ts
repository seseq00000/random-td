import { MAX_SLOTS } from '../core/economy.js'
import type { TileCoord } from '../core/types.js'

/**
 * 나선 필드의 튜닝 값. 적은 바깥 원에서 스폰돼 빙빙 돌며 중앙 코어로 좁혀든다.
 *
 * 경로형(WAYPOINTS)을 대체한다. 경로에서는 "어디에 놓느냐"가 uptime 을 결정했지만,
 * 여기서는 모든 타워가 코어 주변에 모이므로 **사거리가 uptime 을 결정한다** —
 * 사거리 6짜리는 원이 반경 6까지 줄었을 때부터, 3짜리는 3까지 줄었을 때부터 쏜다.
 */

/** 스폰 반경 (타일). 필드 절반(7.5)보다 살짝 안쪽이라 항상 화면에 보인다. */
export const SPAWN_RADIUS_TILES = 7

/** 코어 반경 (타일). 적의 나선 반경이 여기까지 줄면 누출이다. */
export const CORE_RADIUS_TILES = 0.6

/** 스폰부터 코어까지 도는 바퀴 수. 늘리면 "빙빙 돈다"가 강해지고 체류 시간이 길어진다. */
export const REVOLUTIONS = 2.5

/**
 * 반경이 줄어드는 곡선의 지수. 1이면 등속으로 좁혀들고, 클수록 **바깥에 오래 머물다가
 * 막판에 급히 파고든다.**
 *
 * 이게 이 게임에서 사거리를 의미 있게 만드는 유일한 장치다. 경로형에서는 "어디에
 * 놓느냐"가 uptime 을 갈랐지만 나선에서는 모든 타워가 코어 옆에 모이므로, 지수가 1이면
 * 사거리 3짜리와 6짜리가 거의 같은 시간을 쏘게 된다 — 실제로 그렇게 두자 전략 간
 * 격차가 뭉개졌다(기본 경제만으로 클리어 28%).
 *
 * 2로 두면 적이 여정의 절반을 반경 5.4타일 밖에서 보내므로, 그 구간에 닿는 건
 * 저격·관통 같은 장사거리뿐이다. 짧은 사거리는 막판에만 일하고,
 * **보드를 넓힐수록(=역할이 다양할수록) 커버되는 구간이 늘어난다.**
 */
export const RADIUS_CURVE = 2

/**
 * 나선 전체 진행 길이(px). 적 속도는 `speed × 40 px/초` 이므로
 * 이 값이 곧 **주파 시간**이다 (1920px ÷ 60px/초 ≈ 32초 @ BASE_SPEED 1.5).
 *
 * 경로형의 총 길이(48타일 = 1920px)를 그대로 가져왔다 —
 * 밸런스 재측정의 출발점을 기존과 비교 가능하게 두려는 것이다.
 */
export const SPIRAL_LENGTH = 1920

/**
 * 적이 나오는 지점의 각도 — 12시 방향 고정.
 *
 * 처음엔 황금각으로 스폰 각도를 흩어서 원 전체에서 나오게 했지만, **어디서 나오는지가
 * 안 읽혔다.** 한 지점에서 나오면 적이 나선을 따라 한 줄로 늘어서므로 "저기서 나와서
 * 여기로 온다"가 한눈에 들어오고, 스플래시·관통이 줄을 훑는 그림이 살아난다.
 *
 * 겹치지 않는 이유는 `SPAWN_INTERVAL`(0.7초)이다 — 시간차가 곧 나선 위의 간격이 된다.
 */
export const SPAWN_ANGLE = -Math.PI / 2

/**
 * 타워가 자동으로 채워지는 자리 — 코어를 둘러싼 10칸. `MAX_SLOTS` 와 길이가 같아야 한다.
 *
 * **순서가 곧 배치 순서다.** 시계방향으로 돌기 때문에 연달아 배치한 타워끼리 인접하고,
 * 그래서 버프 유닛의 인접 8타일 오라(`combat.ts` auraMultipliers)가 그대로 의미를 갖는다.
 * 앞 8칸은 코어에 딱 붙고, 마지막 2칸만 반경 2다.
 */
export const SLOT_POSITIONS: readonly TileCoord[] = [
  { tx: 6, ty: 6 },
  { tx: 7, ty: 6 },
  { tx: 8, ty: 6 },
  { tx: 8, ty: 7 },
  { tx: 8, ty: 8 },
  { tx: 7, ty: 8 },
  { tx: 6, ty: 8 },
  { tx: 6, ty: 7 },
  { tx: 7, ty: 5 },
  { tx: 7, ty: 9 },
]

// 슬롯 가격표(slots.ts)와 같은 방식으로, 두 상수가 어긋나면 즉시 터뜨린다.
// 자리가 모자라면 슬롯을 사도 배치가 안 되는 조용한 버그가 된다.
if (SLOT_POSITIONS.length !== MAX_SLOTS) {
  throw new Error(
    `field: 슬롯 자리(${SLOT_POSITIONS.length})가 최대 슬롯 수(${MAX_SLOTS})와 다르다`,
  )
}
